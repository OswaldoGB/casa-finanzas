import { PGlite } from "@electric-sql/pglite";
import { readFile } from "node:fs/promises";
import { expect, it } from "vitest";

it("registra consumo y correcciones sin permitir saldos negativos", async () => {
  const db = new PGlite();
  await db.exec(`create role authenticated; create schema auth;
    create table inventory_items(id uuid primary key, household_id uuid not null, quantity numeric not null, created_by uuid not null default '20000000-0000-4000-8000-000000000001', unique(id,household_id));
    create function auth.uid() returns uuid language sql as $$ select '20000000-0000-4000-8000-000000000001'::uuid $$;
    create function public.current_household_id() returns uuid language sql as $$ select coalesce(nullif(current_setting('test.house',true),''),'10000000-0000-4000-8000-000000000001')::uuid $$;
    create function public.has_module_access(text,text) returns boolean language sql as $$ select coalesce(nullif(current_setting('test.access',true),''),'yes')='yes' $$;
    insert into inventory_items(id, household_id, quantity) values ('30000000-0000-4000-8000-000000000001','10000000-0000-4000-8000-000000000001',1.5);`);
  await db.exec(await readFile("supabase/migrations/20261031000052_inventory_packages.sql", "utf8"));
  const item = "30000000-0000-4000-8000-000000000001";
  const initial = await db.query<{ remaining: string }>("select remaining from inventory_packages where item_id=$1", [item]);
  expect(Number(initial.rows[0].remaining)).toBe(1.5);
  await db.query("select inventory_add_packages($1,'Bolsa',4,39,'Caja de Tide')", [item]);
  const packages = await db.query<{ id: string; group_name: string; group_id: string }>("select id,group_name,group_id from inventory_packages where label='Bolsa' order by created_at, id");
  expect(packages.rows).toHaveLength(4);
  expect(new Set(packages.rows.map((row) => row.group_id)).size).toBe(1);
  expect(packages.rows[0].group_name).toBe("Caja de Tide");
  await expect(db.query("update inventory_items set quantity=5 where id=$1", [item])).rejects.toThrow();
  await db.query("select inventory_package_change((select id from inventory_packages where label='Existencia registrada'),'consume',0.5,'')");
  const decimal = await db.query<{ remaining: string }>("select remaining from inventory_packages where label='Existencia registrada'");
  expect(Number(decimal.rows[0].remaining)).toBe(1);
  const id = packages.rows[0].id;
  await db.exec("select set_config('test.access','no',false)");
  await expect(db.query("select inventory_package_change($1,'open',0,'')", [id])).rejects.toThrow();
  await db.exec("select set_config('test.access','yes',false); select set_config('test.house','10000000-0000-4000-8000-000000000002',false)");
  await expect(db.query("select inventory_package_change($1,'open',0,'')", [id])).rejects.toThrow();
  await db.exec("select set_config('test.house','10000000-0000-4000-8000-000000000001',false)");
  await db.query("select inventory_package_change($1,'open',0,'')", [id]);
  await db.query("select inventory_package_change($1,'consume',2,'')", [id]);
  await expect(db.query("select inventory_package_change($1,'consume',38,'')", [id])).rejects.toThrow();
  await db.query("select inventory_package_change($1,'correct',38,'Corrección')", [id]);
  const result = await db.query<{ remaining: number; events: number }>("select remaining, (select count(*)::int from inventory_package_events where package_id=$1) events from inventory_packages where id=$1", [id]);
  expect(Number(result.rows[0].remaining)).toBe(38);
  expect(result.rows[0].events).toBe(4);
  await db.close();
}, 20000);
